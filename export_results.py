"""Export readable results while omitting regenerable dense state matrices."""
import argparse
import copy
import json
from pathlib import Path


def export(source, destination):
    report = json.loads(Path(source).read_text())
    if report.get("status") != "COMPLETE":
        raise ValueError("Only a completed run may be exported.")
    public = copy.deepcopy(report)
    omitted = ["state_a", "state_b", "state_updated"]
    for result in public["results"]:
        for example in result["examples"]:
            for name in omitted:
                example.pop(name, None)
    public["export"] = {"omitted_example_fields": omitted,
                        "note": "All scores, controls, curves and first-four examples per seed are retained. Dense matrices and checkpoints can be regenerated by experiment.py."}
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(public, indent=2, allow_nan=False) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    arguments = parser.parse_args()
    export(arguments.source, arguments.destination)
